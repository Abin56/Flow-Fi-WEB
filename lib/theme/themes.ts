/**
 * The theme catalogue and the saved-preference model.
 *
 *   FlowFi Lime   — the original identity. Hand-tuned in app/globals.css; only Lime has accent / surface options.
 *   Palette themes — Arctic Blue, Graphite Mono, Executive Navy, Slate Blue, Midnight Blue, Ivory Teal: each is just
 *                    a small spec (base + primary [+ secondary]) fed to palette.ts, with a genuinely different identity.
 *   Custom         — the same spec, built by the user.
 *
 * Light / Dark / Match-device stays with next-themes; every theme renders in both modes.
 */

import { type PaletteSpec, BASES, DEFAULT_BASE_ID, PALETTE_ONLY_TOKENS, buildPaletteTokens, findBase } from "./palette";
import { isHex } from "./color";
import {
  DEFAULT_ACCENT_ID,
  DEFAULT_SURFACE_ID,
  MANAGED_TOKEN_NAMES as LIME_TOKEN_NAMES,
  type ContrastCheck,
  type ThemeMode,
  type TokenMap,
  buildTokens,
  findAccent,
  findSurface,
  resolveSelection,
} from "./lime";

export const LIME_ID = "lime";
export const CUSTOM_ID = "custom";

export interface ThemeDef {
  id: string;
  name: string;
  tagline: string;
  /** Absent for FlowFi Lime, which is generated by lime.ts and defined in the stylesheet. */
  spec?: PaletteSpec;
}

/** The curated gallery. Each entry is a different colour identity — no near-duplicates. */
export const THEMES: ThemeDef[] = [
  { id: LIME_ID, name: "FlowFi Lime", tagline: "The original premium lime" },
  { id: "arctic", name: "Arctic Blue", tagline: "Pure white with ocean blue", spec: { base: "white", primary: "#1d62d8" } },
  { id: "graphite", name: "Graphite Mono", tagline: "Black and white, minimal", spec: { base: "black", primary: "#18181b", primaryDark: "#f4f4f5" } },
  { id: "executive", name: "Executive Navy", tagline: "White, navy and steel blue", spec: { base: "white", primary: "#1e3a6e", secondary: "#4f7fd1" } },
  { id: "slate", name: "Slate Blue", tagline: "Soft grey with muted blue", spec: { base: "soft", primary: "#4a68b0", secondary: "#64748b" } },
  { id: "midnight", name: "Midnight Blue", tagline: "Deep navy and cool white", spec: { base: "navy", primary: "#1e40af", primaryDark: "#dce8ff" } },
  { id: "ivory", name: "Ivory Teal", tagline: "Warm ivory with muted teal", spec: { base: "ivory", primary: "#2b7b84" } },
];

export const findTheme = (id: string): ThemeDef | undefined => THEMES.find((t) => t.id === id);

export interface CustomSpec {
  base: string;
  primary: string;
  secondary: string | null;
}

export const DEFAULT_CUSTOM: CustomSpec = { base: DEFAULT_BASE_ID, primary: "#2563eb", secondary: null };

export interface StoredTheme {
  /** "lime", a preset id, or "custom". */
  id: string;
  /** FlowFi Lime's own options — remembered while another theme is active. */
  accent: string;
  surface: string;
  /** The user's custom colours — remembered while another theme is active. */
  custom: CustomSpec;
}

export const DEFAULT_THEME: StoredTheme = { id: LIME_ID, accent: DEFAULT_ACCENT_ID, surface: DEFAULT_SURFACE_ID, custom: DEFAULT_CUSTOM };

export function isDefaultTheme(t: StoredTheme): boolean {
  return t.id === LIME_ID && t.accent === DEFAULT_ACCENT_ID && t.surface === DEFAULT_SURFACE_ID;
}

export interface ResolvedTheme {
  tokens: TokenMap;
  checks: ContrastCheck[];
  /** True for every non-Lime theme: decorative primary-tinted gradient washes are switched off (see globals.css). */
  flat: boolean;
}

export function specOf(t: StoredTheme): PaletteSpec | null {
  if (t.id === LIME_ID) return null;
  if (t.id === CUSTOM_ID) return { base: t.custom.base, primary: t.custom.primary, secondary: t.custom.secondary };
  return findTheme(t.id)?.spec ?? null;
}

export function resolveTheme(t: StoredTheme, mode: ThemeMode): ResolvedTheme {
  const spec = specOf(t);
  if (!spec) {
    const { accent, surface } = resolveSelection(t.accent, t.surface);
    const { tokens, checks } = buildTokens(accent, surface, mode);
    return { tokens, checks, flat: false };
  }
  const { tokens, checks } = buildPaletteTokens(spec, mode);
  return { tokens, checks, flat: true };
}

/** Every custom property any theme may set inline — all are cleared when returning to the stock stylesheet. */
export const MANAGED_TOKEN_NAMES: string[] = [...new Set([...LIME_TOKEN_NAMES, ...PALETTE_ONLY_TOKENS])];

// ---------------------------------------------------------------------------------------------------------------
// Saved preferences
// ---------------------------------------------------------------------------------------------------------------

function sanitizeCustom(raw: unknown): CustomSpec {
  const r = (raw && typeof raw === "object" ? raw : {}) as Partial<CustomSpec>;
  return {
    base: typeof r.base === "string" && findBase(r.base) ? r.base : DEFAULT_CUSTOM.base,
    primary: typeof r.primary === "string" && isHex(r.primary) ? r.primary.toLowerCase() : DEFAULT_CUSTOM.primary,
    secondary: typeof r.secondary === "string" && isHex(r.secondary) ? r.secondary.toLowerCase() : null,
  };
}

/**
 * Reads whatever is in storage and returns a valid choice.
 *   • current shape            → kept (unknown ids repaired field by field)
 *   • last release's {accent, surface} → becomes FlowFi Lime with those options
 *   • anything from the retired multi-theme picker (presets, two-colour, custom seeds) → FlowFi Lime default
 * `migrated` tells the caller the stored value should be rewritten in the current shape.
 */
export function sanitizeStoredTheme(raw: unknown): { theme: StoredTheme; migrated: boolean } {
  if (raw === null || raw === undefined) return { theme: DEFAULT_THEME, migrated: false };
  if (typeof raw !== "object") return { theme: DEFAULT_THEME, migrated: true };
  const r = raw as Partial<StoredTheme> & { presetId?: unknown; seed?: unknown };
  if ("presetId" in r || "seed" in r) return { theme: DEFAULT_THEME, migrated: true };

  const accent = typeof r.accent === "string" && findAccent(r.accent) ? r.accent : DEFAULT_ACCENT_ID;
  const surface = typeof r.surface === "string" && findSurface(r.surface) ? r.surface : DEFAULT_SURFACE_ID;
  const id = typeof r.id === "string" && (r.id === LIME_ID || r.id === CUSTOM_ID || findTheme(r.id)) ? r.id : LIME_ID;
  const custom = sanitizeCustom(r.custom);
  const theme: StoredTheme = { id, accent, surface, custom };
  const wellFormed =
    r.id === id &&
    r.accent === accent &&
    r.surface === surface &&
    !!r.custom &&
    r.custom.base === custom.base &&
    r.custom.primary === custom.primary &&
    (r.custom.secondary ?? null) === custom.secondary;
  return { theme, migrated: !wellFormed };
}

